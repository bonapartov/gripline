class Command(BaseCommand):
    help = "Создаёт страницу /privacy-policy/, если её ещё нет (идемпотентно)."

    def handle(self, *args, **options):
        if WebPage.objects.filter(slug="privacy-policy").exists():
            self.stdout.write(self.style.WARNING(
                "Страница privacy-policy уже существует — ничего не делаю."
            ))
            return

        site = Site.objects.filter(is_default_site=True).first()
        if not site or not site.root_page:
            self.stderr.write(self.style.ERROR("Не найден Site с root_page — некуда добавлять страницу."))
            return

        root_page = site.root_page.specific

        page = WebPage(
            title="Политика конфиденциальности",
            slug="privacy-policy",
            body=[("html", PRIVACY_POLICY_HTML)],
            seo_title="Политика конфиденциальности — Gripline",
            search_description=(
                "Какие данные обрабатывает Gripline и зачем — включая раздел "
                "про калькулятор развесовки карта (/balance/)."
            ),
        )
        root_page.add_child(instance=page)
        page.save_revision().publish()

        self.stdout.write(self.style.SUCCESS(f"Создана страница: {page.full_url}"))
